import assert from "node:assert/strict";
import { createBuilderHarness } from "./builder-harness.mjs";

let allowDeletion = false;
const confirmations = [];
const render = createBuilderHarness("template=Blank+Estimate", (message) => {
  confirmations.push(message);
  return allowDeletion;
});
let state = render();
assert.equal(state.sections.length, 0);
assert.equal(state.progress, 0);
assert.equal(state.totals.directCost, 0);
state.setNewSectionName("   ");
state = render();
state.addEstimateSection();
state = render();
assert.equal(state.sections.length, 0);
state.setNewSectionName(" Groundworks ");
state = render();
state.addEstimateSection();
state = render();
const firstSectionId = state.sections[0].id;
assert.equal(state.sections[0].name, "Groundworks");
assert.ok(state.expandedSections.includes(firstSectionId));
state.setNewSectionName("Structure");
state = render();
state.addEstimateSection();
state = render();
const secondSectionId = state.sections[1].id;

function prepareItem(sectionId, name, quantity, cost, sell = "", method = "Manual") {
  state.setAddItemModal({ sectionId });
  state.setNewItemName(name);
  state.setNewItemQuantity(quantity);
  state.setNewItemUnit("m²");
  state.setNewItemCost(cost);
  state.setNewItemSell(sell);
  state.setNewItemMethod(method);
  state = render();
  state.addEstimateItem();
  state = render();
}
prepareItem(secondSectionId, " Walls ", "3", "100");
assert.equal(state.sections[0].items.length, 0, "Add to the chosen section only");
const wallsId = state.sections[1].items[0].id;
assert.equal(state.sections[1].items[0].name, "Walls");
assert.equal(state.sections[1].items[0].unit, "m²");
assert.equal(state.totals.directCost, 300);
assert.equal(state.sections[1].items[0].sellRate.toFixed(2), "128.21");
assert.equal(state.progress, 100);
state.updateSellRate(secondSectionId, wallsId, 150);
state.updateItemDescription(secondSectionId, wallsId, "External walls");
state.updateItemUnit(secondSectionId, wallsId, "m³");
state.renameSection(secondSectionId, "Building structure");
state.updateQuantity(secondSectionId, wallsId, 4);
state.updateCostRate(secondSectionId, wallsId, 120);
state = render();
assert.equal(state.sections[1].name, "Building structure");
assert.equal(state.sections[1].items[0].name, "External walls");
assert.equal(state.sections[1].items[0].unit, "m³");
assert.equal(state.sections[1].items[0].sellRate, 150);
assert.equal(state.totals.directCost, 480);
assert.equal(state.totals.sellingPrice, 600);
prepareItem(firstSectionId, "Unpriced work", "0", "");
assert.equal(state.sections[0].items[0].quantity, 0, "Zero quantity is not silently changed to one");
assert.equal(state.sections[0].items[0].source, "Not priced");
assert.equal(state.progress, 50);
prepareItem(firstSectionId, "Invalid", "-1", "100");
assert.equal(state.sections[0].items.length, 1);
assert.ok(state.itemError);
prepareItem(firstSectionId, "", "1", "100");
assert.equal(state.sections[0].items.length, 1);
prepareItem(firstSectionId, "Labour", "2", "", "", "Built Up");
const labourId = state.sections[0].items[1].id;
assert.equal(state.buildUpItem.itemId, labourId);
state.addBuildUpLine();
state = render();
const lineId = state.sections[0].items[1].buildUp[0].id;
state.updateBuildUpLine(firstSectionId, labourId, lineId, "rate", 100);
state.updateBuildUpLine(firstSectionId, labourId, lineId, "category", "Labour");
state = render();
assert.equal(state.labourCost, 200);
assert.equal(state.labourHours, 2);
assert.equal(state.totals.directCost, 680);
state.deleteEstimateItem(firstSectionId, labourId);
state.deleteEstimateSection(secondSectionId);
state = render();
assert.equal(state.sections.length, 2, "Cancelled section deletion preserves data");
assert.equal(state.labourCost, 200, "Cancelled item deletion preserves data");
allowDeletion = true;
state.deleteEstimateItem(firstSectionId, labourId);
state = render();
assert.equal(state.labourCost, 0);
assert.equal(state.labourHours, 0);
assert.equal(state.totals.directCost, 480);
assert.equal(state.buildUpItem, null);
state.deleteEstimateSection(secondSectionId);
state = render();
assert.equal(state.totals.directCost, 0);
assert.equal(state.totals.sellingPrice, 0);
assert.equal(state.sections.length, 1);
assert.ok(!state.expandedSections.includes(secondSectionId));
state.deleteEstimateSection(firstSectionId);
state = render();
assert.equal(state.sections.length, 0);
assert.equal(state.progress, 0);
assert.equal(state.addItemModal, null);
assert.equal(confirmations.length, 5);

state.setNewSectionName("Allowances");
state = render();
state.addEstimateSection();
state = render();
const allowanceSectionId = state.sections[0].id;
prepareItem(allowanceSectionId, "Provisional work", "3", "100", "140", "Allowance");
assert.equal(state.sections[0].items[0].source, "Allowance");
assert.equal(state.sections[0].items[0].sellOverridden, true);
assert.equal(state.allowanceItem.sectionId, allowanceSectionId);
state.setAllowanceValue("120");
state = render();
state.applyAllowance();
state = render();
assert.equal(state.sections[0].items[0].sellRate, 140);
assert.equal(state.totals.directCost, 360);
state.deleteEstimateSection(allowanceSectionId);
state = render();
assert.equal(state.allowanceItem, null);
assert.equal(state.totals.directCost, 0);

const templateNames = ["Double Storey Extension", "Loft Conversion", "Full House Renovation",
  "Kitchen Renovation", "Bathroom Renovation", "New Build House", "New Build Bungalow", "General Works"];
const signatures = new Set();
for (const template of templateNames) {
  const templateRender = createBuilderHarness(new URLSearchParams({ template }).toString());
  const estimate = templateRender();
  assert.ok(estimate.sections.length > 0, `${template} has starting sections`);
  signatures.add(JSON.stringify(estimate.sections));
  assert.equal(estimate.totals.directCost, 0);
  assert.equal(estimate.totals.sellingPrice, 0);
  assert.equal(estimate.progress, 0);
  for (const item of estimate.sections.flatMap((section) => section.items)) {
    assert.equal(item.source, "Not priced");
    assert.equal(item.costRate, 0);
    assert.equal(item.sellRate, 0);
  }
}
assert.equal(signatures.size, templateNames.length, "Templates have distinct work structures");
assert.equal(createBuilderHarness("template=toString")().sections.length, 0, "Unknown templates safely start empty");
prepareItem(999, "Missing section", "1", "100");
assert.equal(state.sections.length, 0, "Never add items to a removed section");
console.log("PASS: blank estimates, section/item creation and edits, rates, validation, confirmed/cancelled deletion, totals, drawer cleanup and distinct unpriced templates.");
